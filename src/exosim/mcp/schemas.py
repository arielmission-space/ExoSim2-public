"""Shared schemas for the ExoSim MCP tool layer."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from pathlib import Path


@dataclass(frozen=True)
class KnowledgeSource:
    """Description of a retrieved knowledge source.

    Parameters
    ----------
    path : str
        Repository-relative path of the source file.
    start_line : int
        First line in the retrieved passage.
    end_line : int
        Last line in the retrieved passage.
    score : float
        Normalised lexical score assigned by the retriever.
    text : str
        Retrieved passage text.
    """

    path: str
    start_line: int
    end_line: int
    score: float
    text: str

    def to_dict(self) -> dict[str, Any]:
        """Convert the source to a serialisable dictionary.

        Returns
        -------
        dict
            Serialisable representation of the source.
        """
        return asdict(self)


@dataclass(frozen=True)
class KnowledgeBaseSourcePattern:
    """Description of an approved MCP retrieval source pattern.

    Parameters
    ----------
    pattern : str
        Glob pattern relative to the repository root.
    purpose : str
        Reason this source class is included in retrieval.
    """

    pattern: str
    purpose: str

    def to_dict(self) -> dict[str, str]:
        """Convert the pattern to a serialisable dictionary.

        Returns
        -------
        dict
            Serialisable source pattern description.
        """
        return asdict(self)


@dataclass(frozen=True)
class PipelineDefinition:
    """Description of an ExoSim pipeline exposed by MCP.

    Parameters
    ----------
    name : str
        Stable MCP pipeline name.
    recipe : str
        Python recipe used by the pipeline.
    cli_command : str
        Equivalent ExoSim CLI command.
    required_inputs : tuple[str, ...]
        Required input names for the MCP tool.
    output_description : str
        Expected output generated by the pipeline.
    """

    name: str
    recipe: str
    cli_command: str
    required_inputs: tuple[str, ...]
    output_description: str

    def to_dict(self) -> dict[str, Any]:
        """Convert the definition to a serialisable dictionary.

        Returns
        -------
        dict
            Serialisable pipeline definition.
        """
        data = asdict(self)
        data["required_inputs"] = list(self.required_inputs)
        return data


def resolve_repo_path(
    path: str | Path,
    repo_root: str | Path | None = None,
    *,
    work_dir: str | Path | None = None,
    prefer_work_dir: bool = False,
) -> Path:
    """Resolve a path a tool wants to **read**, confined to the MCP sandbox.

    Relative paths are taken against the repository root (with
    ``prefer_work_dir`` the working directory is tried first, so files produced
    by a run are found by their bare name). The result must fall
    within one of the sandbox's readable roots (the checkout, the working
    directory, or an ``EXOSIM_MCP_ALLOW_DIRS`` entry) or
    :class:`~exosim.mcp.sandbox.PathNotAllowedError` is raised.

    Parameters
    ----------
    path : str or pathlib.Path
        Input path to resolve.
    repo_root : str or pathlib.Path, optional
        Repository root. Defaults to ``EXOSIM_MCP_REPO_ROOT`` or the current
        working directory.
    work_dir : str or pathlib.Path, optional
        Writable working directory. Defaults to ``EXOSIM_MCP_WORK_DIR`` or
        ``<repo_root>/mcp-runs`` (``./mcp-runs`` when the content is packaged).
    prefer_work_dir : bool
        Try a relative path against the working directory before the
        repository root.

    Returns
    -------
    pathlib.Path
        Absolute resolved path, guaranteed inside the sandbox.
    """
    from exosim.mcp.sandbox import Sandbox

    return Sandbox.from_env(repo_root=repo_root, work_dir=work_dir).resolve_read(
        path, prefer_work_dir=prefer_work_dir
    )


def resolve_output_path(
    path: str | Path,
    repo_root: str | Path | None = None,
    *,
    work_dir: str | Path | None = None,
) -> Path:
    """Resolve a path a tool wants to **write**, confined to the working dir.

    Relative paths are taken against the working directory. The result must fall
    inside the sandbox's writable roots (never the checkout itself).
    """
    from exosim.mcp.sandbox import Sandbox

    return Sandbox.from_env(repo_root=repo_root, work_dir=work_dir).resolve_write(path)
