import astropy.units as u
import numpy as np

import exosim.output as output
from exosim.tasks.task import Task


def _barron_1d(x, delta, lx):
    """Barron et al. (2007) 1D response; ``x``, ``delta`` and ``lx`` in the same unit."""
    return np.arctan(np.tanh(0.5 * (0.5 * delta - x) / lx)) - np.arctan(
        np.tanh(0.5 * (-0.5 * delta - x) / lx)
    )


def irf_extent_pixels(delta, lx, tol=1e-6, max_extent=10):
    """
    Number of neighbouring pixels ``K`` (on each side) the IRF kernel must cover.

    It is the smallest ``K >= 0`` such that the 1D response evaluated at the
    centre of the first pixel not covered, ``R((K+1)*delta)``, is below ``tol``
    times the peak ``R(0)``. For vanishing diffusion length ``K=0``.

    Parameters
    ----------
    delta: :class:`astropy.units.Quantity`
        pixel pitch
    lx: :class:`astropy.units.Quantity`
        diffusion length
    tol: float
        relative tolerance
    max_extent: int
        upper bound for K

    Returns
    -------
    int
    """
    d = delta.value
    lxv = lx.to(delta.unit).value
    peak = _barron_1d(0.0, d, lxv)
    for k in range(max_extent + 1):
        if _barron_1d((k + 1) * d, d, lxv) / peak < tol:
            return k
    return max_extent


def irf_axis_response(x, delta, lx, ipd):
    """
    1D IRF response sampled at the positions ``x`` (``Quantity``), with the
    inter-pixel gap zeroed within ``ipd/2`` of every pixel boundary
    ``(k+1/2)*delta``.
    """
    unit = delta.unit
    d = delta.value
    xv = x.to(unit).value
    resp = _barron_1d(xv, d, lx.to(unit).value)
    ipdv = ipd.to(unit).value
    t = np.mod(xv + 0.5 * d, d)
    dist = np.minimum(t, d - t)
    resp[dist < 0.5 * ipdv] = 0.0
    return resp


class CreateIntrapixelResponseFunction(Task):
    """
    It creates the intrapixel response function to be used in the convolution with the focal plane array.


    Returns
    -------
    kernel	: 2D array
            the kernel image
    kernel_delta  : scalar
                    the kernel sampling interval in microns


    Notes
    -----
    This is a default class with standardised inputs and outputs.
    The user can load this class and overwrite the "model" method
    to implement a custom Task to replace this.
    """

    def __init__(self):
        """
        Parameters
        __________
        parameters: dict
            channel parameter dictionary. This is usually parsed from :class:`~exosim.tasks.load.load_options.LoadOptions`
        output: :class:`~exosim.output.output.Output` (optional)
           output file
        """

        self.add_task_param("parameters", "channel parameters dict")
        self.add_task_param("output", "output file", None)

    def execute(self):
        self.info("creating pixel response function")
        parameters = self.get_task_param("parameters")

        kernel, kernel_delta = self.model(parameters)

        output_file = self.get_task_param("output")
        if output_file and issubclass(output_file.__class__, output.Output):
            output_group = output_file.create_group("intrapixel_response_function")
            output_group.write_array(
                "kernel",
                kernel,
            )
            output_group.write_quantity(
                "kernel_delta",
                kernel_delta,
            )

        self.set_output([kernel, kernel_delta])

    def model(self, parameters):
        """
        This model creates the intrapixel response function to be used in the convolution with the focal plane array.
        This intrapixel response function is compatible with the Scipy convolution functions.

        Estimate the detector pixel response function with the prescription of
        Barron et al., PASP, 119, 466-475 (2007).

        The response :math:`R(x)R(y)` is the probability that the charge
        generated by a photon at offset :math:`(x, y)` from the pixel centre is
        collected by that pixel. With a non-zero diffusion length it has tails
        outside the pixel footprint (the charge diffusing into the
        neighbours), so the kernel is sampled over the pixel *and* ``K``
        neighbouring pixels on each side (``K`` is the smallest integer such
        that the response at the centre of the first uncovered pixel is below
        1e-6 of the peak, see :func:`irf_extent_pixels`; ``K=0`` without
        diffusion). The kernel therefore has ``osf*(2K+1)`` samples per axis.
        The inter-pixel gap is zeroed around every pixel boundary.

        The kernel is normalised to sum ``osf**2`` (flat field flux
        conservation): the sub-pixel flux that diffuses to the neighbours is
        lost by the central pixel, not re-distributed inside it.

        Parameters
        ----------
        oversampling: int
                number of samples in each resolving element. The
                final shape of the response function would be shape*osf
        delta_pix: :class:`astropy.units.Quantity`
                Physical size of the detector pixel in microns
        diffusion_length: :class:`astropy.units.Quantity`
                diffusion length in microns
        intra_pix_distance: :class:`astropy.units.Quantity`
                distance between two adjacent detector pixels
                in microns

        Returns
        -------
        kernel	: 2D array
                the kernel image
        kernel_delta  : :class:`astropy.units.Quantity`
                        the kernel sampling interval in microns
        """
        if "oversampling" in parameters["detector"]:
            osf = parameters["detector"]["oversampling"]  # activate for old convolution
        else:
            self.warning(
                "oversampling is not defined in the detector parameters. Oversampling factor is set to 1."
            )
            osf = 1  # activate for old convolution

        delta = parameters["detector"]["delta_pix"]
        if "diffusion_length" in parameters["detector"]:
            lx = parameters["detector"]["diffusion_length"]
        else:
            lx = 0.0 * u.um
        if "intra_pix_distance" in parameters["detector"]:
            ipd = parameters["detector"]["intra_pix_distance"]
        else:
            ipd = 0 * u.um
        lx += 1e-20 * u.um  # to avoid problems if user pass lx=0
        lx = lx.to(delta.unit)

        # the kernel covers the pixel and K neighbouring pixels on each side
        n_ext = irf_extent_pixels(delta, lx)
        size = osf * (2 * n_ext + 1)
        self.debug(f"kernel size: {(size, size)} (extent: +-{n_ext} pixels)")
        # prepare the kernel stamp grid
        kernel_delta = delta / osf
        scale = np.arange(size) - size / 2 + 0.5
        axis_response = irf_axis_response(scale * kernel_delta, delta, lx, ipd)
        kernel_stamp = np.outer(axis_response, axis_response)

        # Normalise the kernel such that a flat field is conserved
        # (the kernel sums to osf**2, i.e. mean 1 on the pixel footprint)
        kernel_stamp /= kernel_stamp.sum()
        kernel_stamp *= osf * osf

        return kernel_stamp, kernel_delta

